def set_language(lang: str) -> None:
    global _lang
    _lang = lang if lang in LANGUAGES else "en"


def language() -> str:
    return _lang


def is_rtl() -> bool:
    return _lang in RTL


def t(key: str, **values) -> str:
    row = STRINGS.get(key)
    if row is None:
        return key
    text = row[list(LANGUAGES).index(_lang)]
    return text.format(**values) if values else text
